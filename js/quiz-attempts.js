/* ═══════════════════════════════════════════════════════════════
   QUIZ ATTEMPTS — shared Supabase-backed store
   ---------------------------------------------------------------
   Persists the quizzes a user attempts on the Quiz tab so their score
   history + analysis SYNC across devices for a logged-in user. Mirrors
   js/saved-questions.js (same public anon key, protected by Row Level
   Security). The Quiz tab (js/tabs/saved-questions.js) also keeps a
   localStorage mirror, so attempts still work offline / when signed out.

   Each attempt is stored as a row with a few queryable columns plus the
   full record in `attempt_data` (items + answers + per-quiz breakdown),
   which is what the analysis / "view solutions" screens replay.

   Exposes window.QuizAttempts:
     .available()          -> bool  (client + a user id are usable)
     .userId()             -> string
     .save(rec)            -> Promise<bool>   (upsert by user_id,attempt_id)
     .list()               -> Promise<rec[]>  (newest first)
     .remove(attemptId)    -> Promise<bool>
     .clear()              -> Promise<bool>    (delete all for this user)

   ─── Supabase schema (run once in the SQL editor) ───────────────
   create table if not exists quiz_attempts (
     id           bigint generated by default as identity primary key,
     user_id      text not null,
     user_email   text,
     attempt_id   text not null,          -- client id, e.g. att_...
     scope        text,                   -- 'all' or a source test_id
     title        text,
     score        numeric default 0,
     max_score    numeric default 0,
     correct      int default 0,
     wrong        int default 0,
     skip         int default 0,
     total        int default 0,
     accuracy     int default 0,
     time_taken   int default 0,
     attempt_data jsonb not null default '{}'::jsonb,  -- items, answers, byQuiz
     attempted_at timestamptz default now(),
     unique (user_id, attempt_id)
   );
   alter table quiz_attempts enable row level security;
   create policy "read quiz attempts"   on quiz_attempts for select using (true);
   create policy "insert quiz attempts" on quiz_attempts for insert with check (true);
   create policy "update quiz attempts" on quiz_attempts for update using (true) with check (true);
   create policy "delete quiz attempts" on quiz_attempts for delete using (true);
   ═══════════════════════════════════════════════════════════════ */
(function () {
  var SUPA_URL  = 'https://deefmrmmjlknotzpceqp.supabase.co';
  var SUPA_ANON = 'eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJpc3MiOiJzdXBhYmFzZSIsInJlZiI6ImRlZWZtcm1tamxrbm90enBjZXFwIiwicm9sZSI6ImFub24iLCJpYXQiOjE3ODQyMTMwNzMsImV4cCI6MjA5OTc4OTA3M30.53-6HdN8umsqrHsaoSNX-o1VFdJbZdN6_mnYZ1bCN8A';

  var _client = null;

  /* Dedicated client with persistSession:false — mirrors saved-questions.js so
     we don't trigger the "Multiple GoTrueClient instances" warning. */
  function client() {
    if (_client) return _client;
    if (!(window.supabase && typeof window.supabase.createClient === 'function')) {
      console.warn('[quiz-attempts] Supabase JS library not loaded');
      return null;
    }
    _client = window.supabase.createClient(SUPA_URL, SUPA_ANON, {
      auth: { persistSession: false, autoRefreshToken: false }
    });
    return _client;
  }

  /* Same stable per-user id logic as saved-questions.js, so an attempt made in
     the app is readable by the same user elsewhere. Falls back to a persistent
     device id when signed out. */
  function userId() {
    try {
      var id = localStorage.getItem('ez_user_uid') || localStorage.getItem('ez_user_email');
      if (id) return id;
      var dev = localStorage.getItem('ez_device_id');
      if (!dev) {
        dev = 'dev_' + Math.random().toString(36).slice(2) + Date.now().toString(36);
        localStorage.setItem('ez_device_id', dev);
      }
      return dev;
    } catch (e) { return null; }
  }

  function userEmail() {
    try { return localStorage.getItem('ez_user_email') || null; } catch (e) { return null; }
  }

  /* Map a client-side attempt record → a DB row. */
  function toRow(rec, uid) {
    return {
      user_id:      uid,
      user_email:   userEmail(),
      attempt_id:   String(rec.id),
      scope:        rec.scope || 'all',
      title:        rec.title || 'Quiz',
      score:        Number(rec.score) || 0,
      max_score:    Number(rec.maxScore) || 0,
      correct:      Number(rec.correct) || 0,
      wrong:        Number(rec.wrong) || 0,
      skip:         Number(rec.skip) || 0,
      total:        Number(rec.total) || 0,
      accuracy:     Number(rec.accuracy) || 0,
      time_taken:   Number(rec.timeTaken) || 0,
      attempt_data: { items: rec.items || [], answers: rec.answers || {}, byQuiz: rec.byQuiz || {} },
      attempted_at: rec.at || new Date().toISOString()
    };
  }

  /* Map a DB row → the client-side attempt record shape the Quiz tab uses. */
  function fromRow(row) {
    var data = row.attempt_data || {};
    return {
      id:        row.attempt_id,
      scope:     row.scope || 'all',
      title:     row.title || 'Quiz',
      at:        row.attempted_at,
      score:     Number(row.score) || 0,
      maxScore:  Number(row.max_score) || 0,
      correct:   Number(row.correct) || 0,
      wrong:     Number(row.wrong) || 0,
      skip:      Number(row.skip) || 0,
      total:     Number(row.total) || 0,
      accuracy:  Number(row.accuracy) || 0,
      timeTaken: Number(row.time_taken) || 0,
      byQuiz:    data.byQuiz || {},
      items:     data.items || [],
      answers:   data.answers || {}
    };
  }

  var QuizAttempts = {
    available: function () { return !!client() && !!userId(); },
    userId: userId,

    save: async function (rec) {
      var c = client(), uid = userId();
      if (!c || !uid || !rec) return false;
      try {
        var res = await c.from('quiz_attempts')
          .upsert(toRow(rec, uid), { onConflict: 'user_id,attempt_id' });
        if (res.error) { console.warn('[quiz-attempts] save failed:', res.error.message); return false; }
        return true;
      } catch (e) { console.warn('[quiz-attempts] save threw:', e); return false; }
    },

    list: async function () {
      var c = client(), uid = userId();
      if (!c || !uid) return [];
      try {
        var res = await c.from('quiz_attempts')
          .select('*').eq('user_id', uid).order('attempted_at', { ascending: false }).limit(50);
        if (res.error) { console.warn('[quiz-attempts] list failed:', res.error.message); return []; }
        return (res.data || []).map(fromRow);
      } catch (e) { console.warn('[quiz-attempts] list threw:', e); return []; }
    },

    remove: async function (attemptId) {
      var c = client(), uid = userId();
      if (!c || !uid || !attemptId) return false;
      try {
        var res = await c.from('quiz_attempts')
          .delete().eq('user_id', uid).eq('attempt_id', String(attemptId));
        if (res.error) { console.warn('[quiz-attempts] remove failed:', res.error.message); return false; }
        return true;
      } catch (e) { console.warn('[quiz-attempts] remove threw:', e); return false; }
    },

    clear: async function () {
      var c = client(), uid = userId();
      if (!c || !uid) return false;
      try {
        var res = await c.from('quiz_attempts').delete().eq('user_id', uid);
        if (res.error) { console.warn('[quiz-attempts] clear failed:', res.error.message); return false; }
        return true;
      } catch (e) { console.warn('[quiz-attempts] clear threw:', e); return false; }
    },

    /* Read the current user's attempts on FULL mock / comprehensive-MCQ tests
       taken in the standalone exam engine (test-engine.html), stored in the
       shared `mock_attempts` table. The engine tags rows with the same
       ez_user_uid/email identity the app uses, so filtering by user_id works.
       Returns raw rows (newest first); [] if the table/policy is absent. */
    mockAttempts: async function () {
      var c = client(), uid = userId();
      if (!c || !uid) return [];
      try {
        var res = await c.from('mock_attempts')
          .select('*').eq('user_id', uid).order('created_at', { ascending: false }).limit(50);
        if (res.error) { console.warn('[quiz-attempts] mockAttempts failed:', res.error.message); return []; }
        return res.data || [];
      } catch (e) { console.warn('[quiz-attempts] mockAttempts threw:', e); return []; }
    }
  };

  window.QuizAttempts = QuizAttempts;
})();
